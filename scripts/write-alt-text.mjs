const commit = process.argv.includes("--commit");
const client = sanity({ write: commit });

const units = await client.fetch(`*[_type == "unit"] | order(code asc){_id, code,
  "coverRef": coverImage.asset._ref, "coverAlt": coverImage.alt,
  gallery[]{_key, alt, "ref": asset._ref}}`);
if (!units.length) die("No apartments found.", "Check the token in .env.local.");

const patches = [];
let set = 0, already = 0;
const unknown = new Set();

for (const u of units) {
  const ops = {};
  if (u.coverRef) {
    const text = ALT[u.coverRef];
    if (!text) unknown.add(u.coverRef);
    else if (u.coverAlt === text) already++;
    else { ops["coverImage.alt"] = text; set++; }
  }
  for (const g of u.gallery ?? []) {
    const text = ALT[g.ref];
    if (!text) { unknown.add(g.ref); continue; }
    if (g.alt === text) { already++; continue; }
    ops[`gallery[_key=="${g._key}"].alt`] = text;
    set++;
  }
  console.log(`  ${u.code}: ${Object.keys(ops).length} to write, of ${(u.gallery?.length ?? 0) + 1} photos`);
  if (Object.keys(ops).length) patches.push([u._id, ops]);
}

console.log(`\n  ${set} to write, ${already} already correct`);
if (unknown.size) {
  die(
    `${unknown.size} photo(s) have no description here.`,
    "Someone added photos since this was written — look at them and add an entry, rather than leaving them on the unit-name fallback.",
  );
}
if (!set) { console.log("\nNothing to do.\n"); process.exit(0); }
if (!commit) { console.log("\nNothing was written. Re-run with --commit to apply.\n"); process.exit(0); }

await patches
  .reduce((t, [id, ops]) => t.patch(id, (p) => p.set(ops)), client.transaction())
  .commit();
console.log("\nDone. Next: npm run i18n:extract, so the Spanish gets these too.\n");
